/** 起動直後（チーム選択前）の既定の対戦カード。バランス型どうしにしてある */
export const DEFAULT_AWAY_TEAM_ID = 'flames';
export const DEFAULT_HOME_TEAM_ID = 'foresters';

/**
 * IDから球団を引く。**見つからなければ例外**にする（存在しないIDでの試合開始は
 * 「名鑑にない球団を選んだ」＝呼び出し側のバグなので、静かに既定へ落とすと気づけない）。
 */
export function teamById(id: TeamId): TeamData {
  const team = TEAMS.find((t) => t.id === id);
  if (!team) throw new Error(`unknown team: ${id}`);
  return team;
}
