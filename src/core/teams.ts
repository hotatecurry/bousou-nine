/**
 * 16球団の選手名鑑（フェーズB-12。説明書p6の16球団／p26-29の名鑑に対応）。
 *
 * **項目体系だけが原作準拠で、球団名・選手名・具体数値はすべて独自**
 * （CLAUDE.md「選手データは仕組み優先・名前は独自」。原作の名称は他社の著作物のため）。
 * 能力値の意味と判定への接続は `roster.ts` の `BatterStats` / `PitcherStats` を参照。
 *
 * ここが持つのは**動かないデータだけ**（名鑑）で、試合中に変化する状態（打順・交代・
 * 投球数）は `TeamRoster` の側が持つ。`createTeamRoster` が名鑑からロスターを組む。
 *
 * ## 表の読み方
 *
 * 説明書p26-29の名鑑が表組みなのに合わせて、1選手＝1行の表形式で書く。列の意味は
 * `FielderRow` / `BenchRow` / `PitcherRow` のコメントにある。数値はすべて 0..1 の
 * レーティング（ERAだけは実数値の防御率）。
 *
 * ## 16球団の作り方（バランスの考え方）
 *
 * **総合力をおおむね揃えたうえで、得意分野を球団ごとに散らす**。強い球団と弱い球団を
 * 作ると「どれを選ぶか」が難易度選択になってしまい、16球団ある意味が薄れる。総合力が
 * 近ければ、選択は**相性と好み**の判断になる（打ち勝つ球団／守り勝つ球団／足でかき回す
 * 球団）。総合力の帯は `tests/teams.test.ts` が固定している（打線・投手陣・控えの
 * 合計レーティングを足した1つの指標で、全16球団が同じ帯に収まることを確かめる）。
 *
 * 一方で**得意分野ははっきり差を付ける**（打線最強のアイアンズは投手陣が最弱、投手王国の
 * ギャラクシーズは打線が最弱）。ここを薄くすると、名前が違うだけの同じ球団が16個
 * 並ぶことになる。テストは「打線1位と投手1位が別の球団であること」も固定している。
 */
import type { BatterStats, FieldingPosition, Handedness, PitcherStats, ThrowArm } from './roster';

/**
 * 打順に入る野手1行：`[守備位置, 名前, BOX, AV, HR, RUN]`。
 * **配列の並びがそのまま打順1〜8番**で、9番は投手が入る（原作にDH制は無い）。
 * 守備位置は投手を除く8つがちょうど1回ずつ現れる（`tests/teams.test.ts` で固定）。
 */
export type FielderRow = readonly [FieldingPosition, string, Handedness, number, number, number];

/**
 * 控え野手1行：`[名前, BOX, AV, HR, RUN]`。
 * 守備位置を持たないのは、**代打は退いた選手の守備位置を引き継ぐ**ため（フェーズB-10）。
 */
export type BenchRow = readonly [string, Handedness, number, number, number];

/**
 * 投手1行：`[名前, ARM, ERA, SPD, 変化(シュート), 変化(カーブ), 変化(フォーク), STM,
 * 打席BOX, 打撃AV, 打撃HR, 打撃RUN]`。
 *
 * **1球団6人**で、原作（説明書p8）と同じく**上4人が先発型・下2人がリリーフ型**
 * （リリーフ型はスタミナが少なく先発向きでない）。型そのものはSTMから導出されるので
 * （`pitcherRole`）、この並び順は「STMが 0.6 以上の4人を先に書く」という約束であって
 * 別の値を持っているわけではない（`tests/teams.test.ts` が並びと型の一致を固定する）。
 *
 * **先頭が既定の先発投手**（試合前に選ばなければこの投手が投げる。フェーズC-15）で、
 * 選ばれなかった5人がブルペンに入る。投手も打席に立つので打撃能力も持つ
 * （総じて非力だが、投手ごとに多少の差はある）。
 *
 * 4人の先発型は**得意分野を散らしてある**（速球型・変化球型・スタミナ型など）。
 * 先発を選ぶことが「どの球で押すか」の判断になるのは、この差があって初めて成立する。
 */
export type PitcherRow = readonly [
  string,
  ThrowArm,
  number,
  number,
  number,
  number,
  number,
  number,
  Handedness,
  number,
  number,
  number,
];

export type TeamId = string;

export interface TeamData {
  /** 内部ID（選手IDの接頭辞にもなる＝球団をまたいで選手IDが衝突しない） */
  id: TeamId;
  /** 球団名（チーム選択画面・勝敗表示） */
  name: string;
  /** スコアボード用の略称。**カタカナ2文字**（列がずれないよう全球団で揃える） */
  short: string;
  /** 打順1〜8番の野手8人 */
  lineup: readonly FielderRow[];
  /** 控え野手3人（代打・代走要員） */
  bench: readonly BenchRow[];
  /** 投手6人（上4人が先発型・下2人がリリーフ型。先頭が既定の先発） */
  pitchers: readonly PitcherRow[];
}

export function fielderRowStats(row: FielderRow): BatterStats {
  return { bats: row[2], average: row[3], power: row[4], run: row[5] };
}

export function benchRowStats(row: BenchRow): BatterStats {
  return { bats: row[1], average: row[2], power: row[3], run: row[4] };
}

export function pitcherRowBatting(row: PitcherRow): BatterStats {
  return { bats: row[8], average: row[9], power: row[10], run: row[11] };
}

export function pitcherRowPitching(row: PitcherRow): PitcherStats {
  return {
    throws: row[1],
    era: row[2],
    speed: row[3],
    breakRight: row[4],
    breakLeft: row[5],
    fork: row[6],
    stamina: row[7],
  };
}

