/**
 * 試合のテンポ（フェーズE-23）。1球ごと・打席ごと・攻守交代ごとの「間」の長さと、
 * 「いつ間を置くか」の判断をここに集約する。
 *
 * **原作の説明書には時間の記載が無い**（ファミスタ'90説明書は操作とルールだけを書いて
 * いる）。テンポは原作の実機映像と突き合わせて詰めるしかない値なので、
 * **散らばっていると調整のたびに探し回ることになる**。そのため各シーンが持っていた
 * 待ち時間の定数（でっかいモードの捕球後の間・CPU投手の間・ちっちゃいモードの
 * 帰結表示）をすべてここへ引き上げ、**実測値が手に入ったらこのファイルだけを
 * 書き換えれば済む**形にしてある。
 *
 * 設計方針：**待ち時間を延ばすだけにしない**。ただ止まっている時間は退屈になるだけなので、
 * どの「間」にも必ず見せるものを割り当てる（1球ごと＝判定コール／打席の切れ目＝次の打者が
 * 打席に入る／攻守交代＝チェンジとイニング表示）。この対応づけは呼び出し側（main.ts の
 * updateInterlude・applyPitchCall）が担い、ここは長さと判断だけを持つ。
 */
import type { Half } from './rules';

/**
 * 1球の判定が確定してから、次の投球を受け付けるまでの間（でっかいモードの settle）。
 * 人間が投手のときは**これが最短間隔**（以降はプレイヤーがKを押すまで待つ）、CPUが
 * 投手のときはこの後さらに CPU_PITCH_INTERVAL_SEC の「間」が乗る。
 * 判定コール（CALL_BANNER_SEC）を読み切れる長さにしてあり、短くすると
 * 「何の判定だったか分からないまま次の球が来る」状態に戻る。
 */
export const PITCH_SETTLE_SEC = 0.9;

/**
 * CPU投手が狙いを決めてから投げ始めるまでの「間」。PITCH_SETTLE_SEC に続けて消化されるので、
 * CPUの投球間隔は「捕球 → PITCH_SETTLE_SEC → CPU_PITCH_INTERVAL_SEC → ワインドアップ」になる。
 */
export const CPU_PITCH_INTERVAL_SEC = 0.7;

/**
 * ちっちゃいモードでプレーの帰結が確定してから、でっかいモードへカット復帰するまでの
 * 見せ時間。アウト/セーフ/安打のバナーが出ている時間でもある。
 *
 * **フェーズWW-71で1秒→1.5秒にし、その間も画面を動かし続けるようにした**（テストプレイ
 * 「画面が切り替わるタイミングが早すぎる」「切り替わる前に一時停止したみたいになる」）。
 * それまでは帰結が決まった瞬間に**ボール・野手・走者がすべてその場で固まり**、1秒止まった
 * 画を見せてから戻っていた＝**「間」ではなく一時停止に見えていた**。いまはこの間も
 * ボールは転がり、野手は惰性で止まり、走者は塁まで走り切る（判定はもう何もしない）。
 * ②「間を延ばすときは間に見せるものとセットで」の、見せるものの側を足した形。
 */
export const PLAY_RESULT_PAUSE_SEC = 1.5;

/**
 * ファウルの帰結が決まってから戻るまで（フェーズWW-71）。**ほかの帰結より長い**：
 * ファウルは打球がフェアの外へ出た瞬間に決まるので、そこで戻ると**打球がどこへ飛んで
 * いったのかを見ないまま**次の球になる（テストプレイ「ファウルになってから画面が
 * 切り替わるのが早すぎる」）。その間ボールはスタンドの方へ転がり続け、走っていた走者は
 * 元の塁へ戻っていく。
 */
export const FOUL_RESULT_PAUSE_SEC = 1.9;

/**
 * 打った瞬間から、ちっちゃいモードへカットするまで（フェーズWW-71）。
 *
 * それまでは接触の瞬間に**全体を静止させる**ヒットストップ（0.05〜0.12秒）を置いていたが、
 * 止まった直後に画面が切り替わるので**手応えではなく引っかかり**に見えていた（テストプレイ
 * 「切り替わる前に一時停止したみたいになる」）。いまは**止めずに、打球がバットから
 * 飛び出していくところを見せてから**カットする（打者は振り抜き、球は打った向きへ飛ぶ）。
 * 守備のプレーは従来どおり接触の瞬間の状態から始まる＝**判定は1つも動かない**。
 */
export const CONTACT_FOLLOW_SEC = 0.16;

/**
 * 1球ごとの判定コール（ストライク/ボール/ファウル）を表示している時間。
 * PITCH_SETTLE_SEC を超えて残ると次の投球に判定コールが重なるので、settle 以下に保つ。
 */
export const CALL_BANNER_SEC = 0.8;

/**
 * CPU投手が銃を構えてから撃つまでの「間」＝**予兆**（フェーズF-26-2。CLAUDE.md ⑧）。
 *
 * 桜井ノウハウ照合：「**人に反応できない動作をするとすっごい理不尽感がある**」。
 * 銃の命中に打者側の回避手段は無い（CLAUDE.md ③）ので、**撃たれること自体が
 * 見えていなければ理不尽になる**。この間はゲーム全体を静止させ、レティクルが打者に
 * 乗った状態とバナーを見せる＝「回避手段が無いことがそのまま緊張感に変わる」
 * （⑧に書いた予兆の要件そのもの）。
 *
 * 長さは他の「間」と同じ基準で決めてある：攻守交代（2.2秒）より短く、打者交代（1.6秒）と
 * 同じくらい＝**1つのことを読み取るのに要る時間**。ここも実測値ではなく設計値なので、
 * テンポ全体と一緒にこのファイルで調整する。
 */
export const GUN_TELEGRAPH_SEC = 1.5;

/**
 * 試合が決着してから、ランの画面（次の相手を選ぶ／ランの終わり）が出るまでの間
 * （フェーズF-26-6）。
 *
 * **勝敗の表示を読み切る時間**：決着の瞬間はサヨナラ本塁打のバナーとスコアボードと
 * 「○○ ノ カチ!」が同時に出ているので、そこへ即座に選択画面をかぶせると
 * **どう終わったのかを見ないまま次の選択をさせる**ことになる。他の「間」と同じ基準
 * （1つのことを読み取るのに要る時間）で、いちばん長い攻守交代（2.2秒）より少し長く取る。
 */
export const GAME_RESULT_PAUSE_SEC = 2.5;

/**
 * 打席の切れ目に置く「間」の種類。
 * - `batterChange`：打者が代わった（三振・四球・打球の決着で打順が進んだ）
 * - `inningChange`：攻守が入れ替わった（3アウト・サヨナラ以外のイニング終了）
 */
export type InterludeKind = 'batterChange' | 'inningChange';

export const INTERLUDE_SEC: Record<InterludeKind, number> = {
  batterChange: 1.6,
  // 攻守交代は「どちらの攻撃になったか」を読ませる必要があるぶん、打者交代より長く取る。
  // ここが短いと、3アウト目の直後に何の予告もなく次の回の投球が始まる（従来の挙動）。
  inningChange: 2.2,
};

/**
 * 「間」を置くかどうかの判断材料。**打席が変わったかを状態から導出する**ための最小の組で、
 * 打席の終わり方（三振/四球/死球/打球/イニング終了）を個別に捕まえるより取りこぼしがない
 * （main.ts の syncPlateAppearance が「1打席1回」の判定に使っているのと同じ考え方）。
 */
export interface AtBatMarker {
  inning: number;
  half: Half;
  /** 攻撃側チームの打順インデックス（0-8） */
  lineupIndex: number;
  /** 試合が終了しているか（勝敗確定後は間を置かず勝敗表示へ進む） */
  over: boolean;
}

/**
 * 2つの時点の間に置くべき「間」を返す（同じ打席が続いているなら null）。
 *
 * イニングの切り替わりを打者の切り替わりより優先するのは、攻守交代では**必ず打者も
 * 代わる**ため（両方に該当したときに短いほうを選ぶと、チェンジの見せ時間が消える）。
 * 試合が終わっていれば何も置かない（勝敗表示を待たせても得るものがない）。
 */
export function interludeBetween(prev: AtBatMarker, next: AtBatMarker): InterludeKind | null {
  if (next.over) return null;
  if (next.inning !== prev.inning || next.half !== prev.half) return 'inningChange';
  if (next.lineupIndex !== prev.lineupIndex) return 'batterChange';
  return null;
}

/**
 * 死球のあと、**CPUの打者が乱闘するかを決めるまでの「間」**（フェーズWW-71）。
 *
 * 乱闘に持ち込むかは**殴られた打者側だけ**が決める（テストプレイ「ぶつけた投手の側が
 * 乱闘するかを決められるのはおかしい」）。人間の投手が CPU の打者にぶつけたときは、
 * 人間は何も押せず CPU の判断を待つことになるので、**判断が見える長さ**を置く＝
 * `デッドボール！` を読んでから、乱闘が始まるか・試合が続くかが分かる（即座に決めると
 * 何が起きたのか読めないまま画面が変わる）。長さは1球ごとの判定の間（`PITCH_SETTLE_SEC`）
 * と同じ基準＝1つのことを読み取るのに要る時間。
 */
export const CPU_BRAWL_DECISION_SEC = 1.1;
